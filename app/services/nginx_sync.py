"""SAAS-029 — `flask nginx-sync`: generate schools.conf and apply it safely.

Runs on the server only (CLI / systemd timer), never in the web process:
the console just queues a request (services/nginx_queue.py).

Safety pipeline, in order:
  1. file lock (two runs never overlap)
  2. render → schools.conf.new (nginx only loads *.conf)
  3. no diff → stop, no reload
  4. name-conflict check against `nginx -T` (every server_name outside
     schools.conf; the *.manasety.ai wildcard is the intended exception)
  5. backup → <backup root>/nginx.bak_<stamp>/schools.conf
  6. atomic replace
  7. `nginx -t`; failure → restore backup, no reload, exit with its output
  8. `nginx -s reload`
  9. verify each changed host: GET https://127.0.0.1/_health with
     --resolve; failure → restore + nginx -t + reload, job failed

Every external command goes through a Runner (tests swap it; no docker
needed). The only commands ever run are listed in Runner.ALLOWED.
"""
from __future__ import annotations

import difflib
import os
import re
import shutil
import subprocess
from dataclasses import dataclass, field
from datetime import datetime, timedelta, timezone
from pathlib import Path

from flask import current_app

GENERATED_HEADER = "# GENERATED by nginx-sync — do not edit"
SLUG_RE = re.compile(r"^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$")   # = ck_schools_slug_format
BLOCK_RE = re.compile(r"^# (school|moved): (\S+).*?^# end \1: \2\n", re.M | re.S)
CERT_WARN_DAYS = 21
LOG_LIMIT = 8000


class SyncError(RuntimeError):
    pass


# ─── runner ──────────────────────────────────────────────────────────

class Runner:
    """The only door to the outside world. `run` executes argv lists
    (never a shell) and only the commands this module needs."""

    def __init__(self, container: str):
        self.container = container

    def _allowed(self, argv: list[str]) -> bool:
        c = self.container
        return argv in (["docker", "exec", c, "nginx", "-t"],
                        ["docker", "exec", c, "nginx", "-T"],
                        ["docker", "exec", c, "nginx", "-s", "reload"]) \
            or (argv[:1] == ["curl"] and "--resolve" in argv) \
            or argv[:3] == ["openssl", "x509", "-enddate"]

    def run(self, argv: list[str], timeout: int = 30) -> tuple[int, str]:
        if not self._allowed(argv):
            raise SyncError(f"refused command: {argv[0]}")
        try:
            p = subprocess.run(argv, capture_output=True, text=True, timeout=timeout, check=False)
        except (OSError, subprocess.TimeoutExpired) as e:
            return 127, type(e).__name__
        return p.returncode, (p.stdout or "") + (p.stderr or "")

    # thin wrappers — what the pipeline calls
    def nginx_test(self):
        return self.run(["docker", "exec", self.container, "nginx", "-t"])

    def nginx_dump(self):
        return self.run(["docker", "exec", self.container, "nginx", "-T"], timeout=60)

    def nginx_reload(self):
        return self.run(["docker", "exec", self.container, "nginx", "-s", "reload"])

    def health(self, host: str) -> tuple[int, str]:
        return self.run(["curl", "-sk", "-o", "-", "-w", "\n%{http_code}", "--max-time", "10",
                         "--resolve", f"{host}:443:127.0.0.1", f"https://{host}/_health"])

    def cert_enddate(self, path: str):
        return self.run(["openssl", "x509", "-enddate", "-noout", "-in", path])


# ─── settings ────────────────────────────────────────────────────────

@dataclass
class Settings:
    conf_dir: Path
    backup_root: Path
    container: str
    cert: str
    cert_dir: str
    cert_file: str
    upstream: str
    base_domain: str
    max_body: str = "12m"

    @classmethod
    def from_app(cls):
        c = current_app.config
        return cls(conf_dir=Path(c["NGINX_CONF_DIR"]), backup_root=Path(c["NGINX_BACKUP_ROOT"]),
                   container=c["NGINX_CONTAINER"], cert=c["NGINX_WILDCARD_CERT"],
                   cert_dir=c["NGINX_CERT_DIR"], cert_file=c["NGINX_CERT_FILE"],
                   upstream=c["NGINX_UPSTREAM"], base_domain=c.get("BASE_DOMAIN") or "manasety.ai")

    @property
    def target(self) -> Path:
        return self.conf_dir / "schools.conf"


# ─── rendering ───────────────────────────────────────────────────────

def _template(name):
    from jinja2 import Environment, FileSystemLoader, StrictUndefined
    root = Path(current_app.root_path).parent / "deploy" / "nginx"
    env = Environment(loader=FileSystemLoader(str(root)), undefined=StrictUndefined,
                      keep_trailing_newline=True, autoescape=False)
    return env.get_template(name)


def _checked_slug(slug: str) -> str:
    """Re-check the DB value before it reaches nginx syntax (defence in
    depth on top of ck_schools_slug_format)."""
    if not isinstance(slug, str) or not SLUG_RE.match(slug):
        raise SyncError(f"invalid slug in DB: {slug!r}")
    return slug


def wanted_slugs() -> list[str]:
    """active + suspended schools get a block (the app shows the blocked
    page); archived ones fall back to the wildcard."""
    from ..models import School
    rows = School.query.filter(School.status.in_(("active", "suspended"))).all()
    return sorted(_checked_slug(s.slug) for s in rows)


def moved_slugs() -> list[tuple[str, str]]:
    """(old, new) slugs still inside their redirect window (SAAS-032)."""
    try:
        from ..models import SchoolSlugHistory
    except ImportError:
        return []
    from ..models import School
    now = datetime.now(timezone.utc).replace(tzinfo=None)
    out = []
    for h in SchoolSlugHistory.query.all():
        until = h.redirect_until.replace(tzinfo=None) if h.redirect_until else None
        if until is not None and until >= now:
            school = School.query.get(h.school_id)
            if school is not None and school.status in ("active", "suspended"):
                out.append((_checked_slug(h.old_slug), _checked_slug(school.slug)))
    return sorted(out)


def render_block(st: Settings, slug: str) -> str:
    return _template("school.conf.j2").render(
        slug=slug, host=f"{slug}.{st.base_domain}", cert=st.cert, cert_dir=st.cert_dir,
        upstream=st.upstream, max_body=st.max_body)


def render_redirect(st: Settings, old: str, new: str) -> str:
    return _template("redirect.conf.j2").render(
        slug=old, new_slug=new, host=f"{old}.{st.base_domain}", cert=st.cert,
        cert_dir=st.cert_dir, upstream=st.upstream)


def split_blocks(text: str) -> dict[tuple[str, str], str]:
    return {(m.group(1), m.group(2)): m.group(0) for m in BLOCK_RE.finditer(text or "")}


def render_file(st: Settings, *, only: str | None = None, current: str = "") -> str:
    blocks: dict[tuple[str, str], str] = {}
    for slug in wanted_slugs():
        blocks[("school", slug)] = render_block(st, slug)
    for old, new in moved_slugs():
        blocks[("moved", old)] = render_redirect(st, old, new)
    if only is not None:
        # Touch one slug; every other block stays exactly as deployed.
        keep = {k: v for k, v in split_blocks(current).items() if k[1] != only}
        keep.update({k: v for k, v in blocks.items() if k[1] == only})
        blocks = keep
    body = "\n".join(blocks[k] for k in sorted(blocks, key=lambda k: (k[1], k[0])))
    return f"{GENERATED_HEADER}\n\n{body}"


def hosts_in(text: str) -> set[str]:
    return {h for line in re.findall(r"^\s*server_name\s+([^;]+);", text, re.M)
            for h in line.split()}


# ─── conflict check ─────────────────────────────────────────────────

def foreign_server_names(dump: str) -> set[str]:
    """Every server_name in `nginx -T` output except those from schools.conf.
    Wildcards / regex names are skipped (Lamma's *.manasety.ai is the
    intended catch-all that explicit names override)."""
    names, current_file = set(), ""
    for line in dump.splitlines():
        m = re.match(r"^# configuration file (\S+):", line)
        if m:
            current_file = m.group(1)
            continue
        if current_file.endswith("/schools.conf"):
            continue
        m = re.match(r"^\s*server_name\s+([^;]+);", line)
        if m:
            for name in m.group(1).split():
                if name.startswith(("*", "~", ".")) or name == "_":
                    continue
                names.add(name.lower())
    return names


# ─── certificate ────────────────────────────────────────────────────

def cert_days_left(runner: Runner, st: Settings) -> tuple[int | None, str | None]:
    rc, out = runner.cert_enddate(st.cert_file)
    m = re.search(r"notAfter=(.+)", out or "")
    if rc != 0 or not m:
        return None, "تعذّرت قراءة تاريخ انتهاء الشهادة."
    try:
        end = datetime.strptime(m.group(1).strip(), "%b %d %H:%M:%S %Y %Z").replace(tzinfo=timezone.utc)
    except ValueError:
        return None, "تعذّرت قراءة تاريخ انتهاء الشهادة."
    days = (end - datetime.now(timezone.utc)).days
    return days, (f"الشهادة تنتهي خلال {days} يوم." if days < CERT_WARN_DAYS else None)


# ─── the pipeline ───────────────────────────────────────────────────

@dataclass
class SyncResult:
    status: str                       # unchanged | applied | check | dry_run | failed
    diff: str = ""
    changed_hosts: list[str] = field(default_factory=list)
    slugs: list[str] = field(default_factory=list)
    log: list[str] = field(default_factory=list)
    cert_days_left: int | None = None
    warnings: list[str] = field(default_factory=list)

    def say(self, msg):
        self.log.append(msg)


class _Lock:
    """flock on the server; an exclusive lock file elsewhere (dev/tests)."""

    def __init__(self, path: Path):
        self.path = path
        self.fh = None

    def __enter__(self):
        self.path.parent.mkdir(parents=True, exist_ok=True)
        self.fh = open(self.path, "a+")
        try:
            import fcntl
            try:
                fcntl.flock(self.fh, fcntl.LOCK_EX | fcntl.LOCK_NB)
            except OSError:
                self.fh.close()
                raise SyncError("another nginx-sync is running") from None
        except ImportError:
            try:
                import msvcrt
                msvcrt.locking(self.fh.fileno(), msvcrt.LK_NBLCK, 1)
            except OSError:
                self.fh.close()
                raise SyncError("another nginx-sync is running") from None
        return self

    def __exit__(self, *exc):
        try:
            self.fh.close()
        except Exception:  # noqa: BLE001
            pass


def _diff(old: str, new: str) -> str:
    return "".join(difflib.unified_diff(old.splitlines(True), new.splitlines(True),
                                        "schools.conf", "schools.conf.new"))


def _healthy(runner: Runner, host: str) -> bool:
    """200 + {"ok": true} from the app's /_health on that host."""
    import json
    rc, out = runner.health(host)
    if rc != 0 or "\n" not in (out or ""):
        return False
    body, code = out.rsplit("\n", 1)
    try:
        return code.strip() == "200" and json.loads(body).get("ok") is True
    except ValueError:
        return False


def run_sync(*, runner: Runner | None = None, st: Settings | None = None, check: bool = False,
             dry_run: bool = False, only: str | None = None) -> SyncResult:
    st = st or Settings.from_app()
    runner = runner or Runner(st.container)
    res = SyncResult(status="failed")
    if only is not None:
        only = _checked_slug(only)
    marker = st.conf_dir / ".nginx-sync.pending"
    with _Lock(st.conf_dir / ".nginx-sync.lock"):
        current = st.target.read_text(encoding="utf-8") if st.target.exists() else ""
        interrupted = marker.exists()
        new = render_file(st, only=only, current=current)
        res.slugs = wanted_slugs()
        res.diff = _diff(current, new)
        res.changed_hosts = sorted(
            {h for k, v in split_blocks(new).items() if split_blocks(current).get(k) != v
             for h in hosts_in(v)})
        days, warn = cert_days_left(runner, st)
        res.cert_days_left = days
        if warn:
            res.warnings.append(warn)
            res.say(f"warning: {warn}")
        if check:
            res.status = "check"
            return res
        if interrupted:
            res.say("previous run was interrupted after writing — re-validating")
        if new == current and not interrupted:
            res.status = "unchanged"
            res.say("no changes — nothing written, no reload")
            return res
        rc, dump = runner.nginx_dump()
        if rc != 0:
            res.say(f"nginx -T failed:\n{dump}")
            return res
        clash = sorted(hosts_in(new) & foreign_server_names(dump))
        if clash:
            res.say("refused: server_name already used outside schools.conf: " + ", ".join(clash))
            return res
        if dry_run:
            res.status = "dry_run"
            return res
        staged = st.conf_dir / "schools.conf.new"
        staged.write_text(new, encoding="utf-8")
        stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
        backup_dir = st.backup_root / f"nginx.bak_{stamp}"
        backup_dir.mkdir(parents=True, exist_ok=True)
        backup = backup_dir / "schools.conf"
        if st.target.exists():
            shutil.copy2(st.target, backup)
        else:
            backup.write_text("", encoding="utf-8")
        res.say(f"backup: {backup}")
        marker.write_text(stamp, encoding="utf-8")
        os.replace(staged, st.target)

        def restore(why):
            shutil.copy2(backup, st.target)
            res.say(f"rolled back ({why})")

        def done():
            marker.unlink(missing_ok=True)
            return res

        rc, out = runner.nginx_test()
        if rc != 0:
            restore("nginx -t failed")
            res.say(f"nginx -t:\n{out}")
            return done()
        rc, out = runner.nginx_reload()
        if rc != 0:
            restore("reload failed")
            runner.nginx_test()
            runner.nginx_reload()
            res.say(f"reload:\n{out}")
            return done()
        school_hosts = {f"{s}.{st.base_domain}" for s in res.slugs}
        # Removed blocks have nothing to verify; redirect blocks answer
        # 301 rather than /_health.
        bad = [h for h in res.changed_hosts if h in school_hosts and not _healthy(runner, h)]
        if bad:
            restore("verification failed: " + ", ".join(bad))
            runner.nginx_test()
            runner.nginx_reload()
            return done()
        res.status = "applied"
        res.say(f"applied: {len(res.changed_hosts)} host(s) changed")
        return done()


# ─── queue runner ───────────────────────────────────────────────────

STALE_RUNNING = timedelta(minutes=30)
RETRY_AFTER = timedelta(minutes=10)
MAX_RETRIES = 3


def _retry_after_failure(now) -> None:
    """A failed sync is retried (every 10 min, at most 3 times in a row)
    instead of waiting for someone to press "sync"."""
    from ..extensions import db
    from ..models import PlatformJob
    recent = (PlatformJob.query.filter_by(kind="nginx_sync")
              .order_by(PlatformJob.id.desc()).limit(MAX_RETRIES).all())
    if not recent or recent[0].status != "failed":
        return
    if len(recent) == MAX_RETRIES and all(j.status == "failed" and (j.reason or "").startswith("retry")
                                          for j in recent):
        return                      # gave up; a person has to look
    last = recent[0].finished_at
    last = last if last is None or last.tzinfo else last.replace(tzinfo=timezone.utc)
    if last is not None and now - last < RETRY_AFTER:
        return
    db.session.add(PlatformJob(kind="nginx_sync", status="pending", reason="retry after failure"))
    db.session.commit()


def run_queue(**kw) -> SyncResult | None:
    """Claim every pending job, run the pipeline once, record the outcome."""
    from ..extensions import db
    from ..models import PlatformJob
    from .audit import redact
    now = datetime.now(timezone.utc)
    # a run killed mid-way (timeout, OOM) never recorded its outcome
    for j in PlatformJob.query.filter_by(kind="nginx_sync", status="running").all():
        started = j.started_at if j.started_at is None or j.started_at.tzinfo else \
            j.started_at.replace(tzinfo=timezone.utc)
        if started is None or now - started > STALE_RUNNING:
            j.status, j.finished_at = "failed", now
            j.log = (j.log or "") + "\ninterrupted (no result recorded)"
    db.session.commit()
    jobs = PlatformJob.query.filter_by(kind="nginx_sync", status="pending").all()
    if not jobs:
        _retry_after_failure(now)
        jobs = PlatformJob.query.filter_by(kind="nginx_sync", status="pending").all()
    if not jobs:
        return None
    for j in jobs:
        j.status, j.started_at = "running", now
    db.session.commit()
    try:
        res = run_sync(**kw)
    except Exception as e:  # noqa: BLE001
        res = SyncResult(status="failed", log=[f"error: {type(e).__name__}: {e}"])
    ok = res.status in ("applied", "unchanged")
    text = "\n".join(res.log)
    if len(text) > LOG_LIMIT:
        text = text[:LOG_LIMIT] + "\n…(truncated)"
    for j in jobs:
        j.status = "succeeded" if ok else "failed"
        j.finished_at = datetime.now(timezone.utc)
        j.log = redact(text)
        j.result = {"slugs": res.slugs, "cert_days_left": res.cert_days_left,
                    "warnings": res.warnings, "status": res.status}
    db.session.commit()
    return res
